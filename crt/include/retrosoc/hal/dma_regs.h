#ifndef RETROSOC_HAL_DMA_REGS_H
#define RETROSOC_HAL_DMA_REGS_H

#include <stdint.h>

#include <retrosoc/core/soc.h>

#define RS_DMA_REG_IP_ID              UINT32_C(0x000)
#define RS_DMA_REG_IP_VERSION         UINT32_C(0x004)
#define RS_DMA_REG_CAPABILITY         UINT32_C(0x008)
#define RS_DMA_REG_GLOBAL_CTRL        UINT32_C(0x00C)
#define RS_DMA_REG_GLOBAL_STATUS      UINT32_C(0x010)
#define RS_DMA_REG_IRQ_STATE          UINT32_C(0x014)
#define RS_DMA_REG_IRQ_ENABLE         UINT32_C(0x018)
#define RS_DMA_REG_IRQ_TEST           UINT32_C(0x01C)
#define RS_DMA_REG_ERROR_SUMMARY      UINT32_C(0x020)
#define RS_DMA_REG_REQUEST_STATUS     UINT32_C(0x024)

#define RS_DMA_CH_BASE                UINT32_C(0x100)
#define RS_DMA_CH_STRIDE              UINT32_C(0x080)
#define RS_DMA_CH_REG_CTRL            UINT32_C(0x00)
#define RS_DMA_CH_REG_CFG             UINT32_C(0x04)
#define RS_DMA_CH_REG_SRC_ADDR        UINT32_C(0x08)
#define RS_DMA_CH_REG_DST_ADDR        UINT32_C(0x0C)
#define RS_DMA_CH_REG_BYTE_COUNT      UINT32_C(0x10)
#define RS_DMA_CH_REG_REQUEST_SEL     UINT32_C(0x14)
#define RS_DMA_CH_REG_BURST_CFG       UINT32_C(0x18)
#define RS_DMA_CH_REG_EVENT_ENABLE    UINT32_C(0x1C)
#define RS_DMA_CH_REG_STATUS          UINT32_C(0x20)
#define RS_DMA_CH_REG_EVENT_STATUS    UINT32_C(0x24)
#define RS_DMA_CH_REG_ERROR_STATUS    UINT32_C(0x28)
#define RS_DMA_CH_REG_ERROR_ADDR      UINT32_C(0x2C)
#define RS_DMA_CH_REG_CURRENT_SRC     UINT32_C(0x30)
#define RS_DMA_CH_REG_CURRENT_DST     UINT32_C(0x34)
#define RS_DMA_CH_REG_REMAINING       UINT32_C(0x38)
#define RS_DMA_CH_REG_BYTES_DONE      UINT32_C(0x3C)
#define RS_DMA_CH_REG_STALL_CYCLES_LO UINT32_C(0x40)
#define RS_DMA_CH_REG_STALL_CYCLES_HI UINT32_C(0x44)
#define RS_DMA_CH_REG_TCD_HEAD        UINT32_C(0x48)
#define RS_DMA_CH_REG_TCD_COUNT       UINT32_C(0x4C)
#define RS_DMA_CH_REG_CRC_EXPECTED    UINT32_C(0x50)
#define RS_DMA_CH_REG_CRC_RESULT      UINT32_C(0x54)

#define RS_DMA_GLOBAL_CTRL_RESET      UINT32_C(0x00000001)
#define RS_DMA_CH_CTRL_START          UINT32_C(0x00000001)
#define RS_DMA_CH_CTRL_SUSPEND        UINT32_C(0x00000002)
#define RS_DMA_CH_CTRL_RESUME         UINT32_C(0x00000004)
#define RS_DMA_CH_CTRL_ABORT          UINT32_C(0x00000008)
#define RS_DMA_CH_CTRL_RESET          UINT32_C(0x00000010)

#define RS_DMA_CH_CFG_KIND_SHIFT      0U
#define RS_DMA_CH_CFG_KIND_MASK       UINT32_C(0x00000007)
#define RS_DMA_CH_CFG_WIDTH_SHIFT     4U
#define RS_DMA_CH_CFG_WIDTH_MASK      UINT32_C(0x00000030)
#define RS_DMA_CH_CFG_SRC_INCREMENT   UINT32_C(0x00000040)
#define RS_DMA_CH_CFG_DST_INCREMENT   UINT32_C(0x00000080)
#define RS_DMA_CH_CFG_PRIORITY_SHIFT  8U
#define RS_DMA_CH_CFG_PRIORITY_MASK   UINT32_C(0x00000300)
#define RS_DMA_CH_CFG_CRC_ENABLE      UINT32_C(0x00000400)
#define RS_DMA_CH_CFG_CRC_FINAL       UINT32_C(0x00000800)

#define RS_DMA_STATUS_BUSY            UINT32_C(0x00000001)
#define RS_DMA_STATUS_SUSPENDED       UINT32_C(0x00000002)
#define RS_DMA_STATUS_DONE            UINT32_C(0x00000004)
#define RS_DMA_STATUS_ABORTED         UINT32_C(0x00000008)
#define RS_DMA_STATUS_ERROR           UINT32_C(0x00000010)
#define RS_DMA_STATUS_STREAM_LAST     UINT32_C(0x00000020)

#define RS_DMA_EVENT_DONE             UINT32_C(0x00000001)
#define RS_DMA_EVENT_HALF             UINT32_C(0x00000002)
#define RS_DMA_EVENT_ERROR            UINT32_C(0x00000004)
#define RS_DMA_EVENT_ALL              (RS_DMA_EVENT_DONE | RS_DMA_EVENT_HALF | RS_DMA_EVENT_ERROR)

#define RS_DMA_ERROR_CODE_MASK        UINT32_C(0x0000000F)
#define RS_DMA_ERROR_RESPONSE_SHIFT   4U
#define RS_DMA_ERROR_RESPONSE_MASK    UINT32_C(0x00000030)
#define RS_DMA_ERROR_READ             UINT32_C(0x00000040)
#define RS_DMA_ERROR_STREAM_LAST      UINT32_C(0x00000100)

#define RS_DMA_CHANNEL_COUNT          8U
#define RS_DMA_CHANNEL_HP             6U
#define RS_DMA_CHANNEL_RESERVED       7U
#define RS_DMA_MAX_BURST_BEATS        16U
#define RS_DMA_DATA_WIDTH_BITS        32U

#define RS_DMA_CHANNEL_OFFSET(channel, offset)                                                     \
    (RS_DMA_CH_BASE + ((uint32_t)(channel)*RS_DMA_CH_STRIDE) + (offset))
#define RS_DMA_REG(offset) RS_SOC_REG32(RS_SOC_APB4_DMA_BASE, (offset))
#define RS_DMA_CH_REG(channel, offset)                                                             \
    RS_SOC_REG32(RS_SOC_APB4_DMA_BASE, RS_DMA_CHANNEL_OFFSET((channel), (offset)))

#endif
