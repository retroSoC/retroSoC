#!/usr/bin/env python3
"""Generate core-STA constraints from the active SoC clock/reset inventory."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT))
from scripts.rtl.generate_pin_map import read_map  # noqa: E402
from scripts.check_clock_reset_domains import validate  # noqa: E402
from scripts.setup_helpers import atomic_write  # noqa: E402


def require_object(value: Any, field: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ValueError(f"{field} must be an object")
    return value


def require_string(value: Any, field: str) -> str:
    if not isinstance(value, str) or not value:
        raise ValueError(f"{field} must be a non-empty string")
    return value


def parse_document(path: Path, pin_map: Path) -> tuple[list[dict[str, Any]], list[str]]:
    validate(path, ROOT)
    document = require_object(json.loads(path.read_text(encoding="utf-8")), "domain map")
    pads, _ = read_map(pin_map)
    pad_names = {pad.name for pad in pads}
    reset_ports = document.get("reset_ports")
    if not isinstance(reset_ports, list) or not reset_ports:
        raise ValueError("reset_ports must be a non-empty list")
    parsed_resets = [require_string(port, "reset_ports entry") for port in reset_ports]
    if len(parsed_resets) != len(set(parsed_resets)):
        raise ValueError("reset_ports contains duplicates")
    for port in parsed_resets:
        if port not in pad_names:
            raise ValueError(f"reset port is not declared in pin map: {port}")

    domains = document["domains"]
    names = {domain["name"] for domain in domains}
    for domain in domains:
        sta = domain["sta"]
        source_port = sta.get("source_port")
        if source_port is not None and source_port not in pad_names:
            raise ValueError(f"domain {domain['name']} source port is not declared in pin map")
        source_domain = sta.get("source_domain")
        if source_domain is not None and source_domain not in names:
            raise ValueError(f"domain {domain['name']} source domain is not declared")
    return domains, parsed_resets


def render(domains: list[dict[str, Any]], reset_ports: list[str]) -> str:
    lines = [
        "# Generated by physical/smoke/sta/opensta/generate_sdc.py; do not edit.",
        "# Core-STA baseline: pad/package timing is intentionally excluded.",
        "",
        "proc require_pins {label name} {",
        "  set objects [get_pins -quiet $name]",
        "  if {$objects eq \"\"} {",
        "    error \"required SDC object is missing: $label ($name)\"",
        "  }",
        "  return $objects",
        "}",
        "",
        "proc require_net_driver_pin {label name} {",
        "  set net [get_nets -quiet $name]",
        "  if {$net eq \"\"} {",
        "    error \"required SDC net is missing: $label ($name)\"",
        "  }",
        "  set drivers [get_pins -quiet -filter \"direction == output\" -of_objects $net]",
        "  if {[llength $drivers] != 1} {",
        "    error \"required SDC net must have one output driver: $label ($name)\"",
        "  }",
        "  return $drivers",
        "}",
        "",
        "proc require_ports {label name} {",
        "  set objects [get_ports -quiet $name]",
        "  if {$objects eq \"\"} {",
        "    error \"required SDC object is missing: $label ($name)\"",
        "  }",
        "  return $objects",
        "}",
        "",
    ]
    pin_variables: dict[str, str] = {}
    for domain in domains:
        name = domain["name"]
        sta = domain["sta"]
        object_type = sta.get("object_type", "pin")
        if object_type == "port":
            pin_variable = f"clk_{name}_port"
            object_name = sta["source_port"]
            lines.append(
                f"set {pin_variable} [require_ports \"clock {name}\" {{{object_name}}}]"
            )
        elif object_type == "net_driver":
            pin_variable = f"clk_{name}_pin"
            lines.append(
                f"set {pin_variable} [require_net_driver_pin \"clock {name}\" "
                f"{{{sta['net']}}}]"
            )
        else:
            pin_variable = f"clk_{name}_pin"
            lines.append(
                f"set {pin_variable} [require_pins \"clock {name}\" {{{sta['pin']}}}]"
            )
        pin_variables[name] = pin_variable
        period = f"{float(sta['period_ns']):.12g}"
        source_domain = sta.get("source_domain")
        if source_domain is None:
            lines.append(f"create_clock -name clk_{name} -period {period} ${pin_variable}")
        else:
            divide_by = sta.get("divide_by", 1)
            if not isinstance(divide_by, int) or isinstance(divide_by, bool) or divide_by < 1:
                raise ValueError("generated clock division must be a positive integer")
            lines.append(
                f"create_generated_clock -name clk_{name} -source ${pin_variables[source_domain]} "
                f"-divide_by {divide_by} ${pin_variable}"
            )
        lines.append("")

    clock_names = " ".join(f"clk_{domain['name']}" for domain in domains)
    lines.extend(
        [
            f"set_clock_uncertainty -setup 0.2 [get_clocks {{{clock_names}}}]",
            f"set_clock_uncertainty -hold 0.1 [get_clocks {{{clock_names}}}]",
            "",
        ]
    )
    for domain in domains:
        lines.append(f"set_clock_transition 0.1 [get_clocks {{clk_{domain['name']}}}]")
    lines.append("")
    groups: dict[str, list[str]] = {}
    for domain in domains:
        groups.setdefault(domain["sta"]["async_group"], []).append(f"clk_{domain['name']}")
    if len(groups) > 1:
        lines.append("set_clock_groups -name retrosoc_async -asynchronous \\")
        group_items = list(groups.values())
        for index, clocks in enumerate(group_items):
            continuation = " \\" if index != len(group_items) - 1 else ""
            lines.append(f"  -group [get_clocks {{{' '.join(clocks)}}}]{continuation}")
        lines.append("")

    for reset_port in reset_ports:
        lines.extend(
            [
                f"set reset_{reset_port} [get_ports {{{reset_port}}}]",
                f"if {{$reset_{reset_port} eq \"\"}} {{",
                f"  error \"required reset port is missing: {reset_port}\"",
                "}",
                f"set_false_path -from $reset_{reset_port}",
                "",
            ]
        )
    lines.extend(
        [
            "# This profile closes sequential core paths only. Board and pad timing",
            "# are supplied by a later board-specific SDC profile.",
            "set_false_path -from [all_inputs]",
            "set_false_path -to [all_outputs]",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--domains", type=Path, required=True)
    parser.add_argument("--pin-map", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--xin-hz", type=int, default=24000000)
    args = parser.parse_args()
    try:
        domains, reset_ports = parse_document(args.domains, args.pin_map)
        document = json.loads(args.domains.read_text())
        p7 = document.get("clock_contract") == "TINY-R2-P7"
        if p7 and args.xin_hz not in (24000000, 48000000, 96000000):
            raise ValueError("unsupported Tiny external clock")
        if p7 and args.xin_hz != 24000000:
            aon = next(domain for domain in domains if domain["name"] == "aon")
            external = {**aon, "name": "external", "sta": {**aon["sta"],
                        "period_ns": 1e9 / args.xin_hz}}
            aon["sta"] = {"source_domain": "external", "period_ns": 1e9 / 24000000,
                          "divide_by": args.xin_hz // 24000000, "async_group": "core",
                          "pin": "u_soc.u_clock_backend.gen_ref_divided.u_ref_div/clk_o"}
            domains.insert(0, external)
        if p7:
            # These sources run even while the muxes select their undivided
            # inputs. Their handover synchronizers still require real clocks.
            for divisor in (2, 4):
                domains.append({"name": f"sys_div{divisor}", "sta": {
                    "source_domain": "system", "period_ns": 1e9 * divisor / 24000000,
                    "divide_by": divisor, "async_group": "core", "object_type": "net_driver",
                    "net": f"u_soc.u_clock_backend.s_div{divisor}_clk"}})
            domains.append({"name": "clkout_source", "sta": {
                "source_domain": "aon", "period_ns": 1e9 / 24000000,
                "divide_by": 1, "async_group": "core", "object_type": "net_driver",
                "net": "u_soc.u_clock_output.s_src_clk"}})
        result = render(domains, reset_ports)
        if p7:
            result += "\n# P7 SAFE24 boot scenario; this does not qualify active PLL timing.\n"
            for mux in ("u_sys_mux", "u_mem_mux", "u_pclk_div2_mux", "u_pclk_mux"):
                result += (f"set_case_analysis 0 [require_pins {{P7 SAFE24 selection}} "
                           f"{{u_soc.u_clock_backend.{mux}/select_i}}]\n")
                # select_i passes through sequential handshake state. A static
                # mode must also select its settled gate state; setting only
                # the request cannot prune the other live clock in STA.
                for side, enabled in ((0, 1), (1, 0)):
                    result += (f"set_case_analysis {enabled} [require_net_driver_pin "
                               f"{{P7 SAFE24 settled gate}} "
                               f"{{u_soc.u_clock_backend.{mux}/r_enable{side}}}]\n")
            result += "# CLKOUT retains its reset REF24 source in this boot scenario.\n"
            for bit in (1, 2):
                result += (f"set_case_analysis 0 [require_net_driver_pin {{P7 CLKOUT source}} "
                           f"{{u_soc.u_clock_output.s_cfg_q_{bit}_}}]\n")
        atomic_write(args.output, result)
    except (OSError, ValueError, json.JSONDecodeError) as error:
        parser.error(str(error))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
