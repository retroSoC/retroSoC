def _emit_flac(program: Program) -> None:
    """Emit the bounded native-FLAC metadata and frame driver."""

    program.label("flac")
    program.op("movi r0, 0")
    program.op("movi r1, 0x4400")
    program.op("movi r2, 208")
    program.op("loop_setup 0, r2")
    program.label("flac_state_clear_loop")
    program.op("st32 r1, r0, 0")
    program.op("movi r3, 4")
    program.op("add r1, r1, r3")
    program.op("loop_back 0, flac_state_clear_loop")
    program.op("movi r1, 2")
    _store(program, 1, WAV_STATE["format"])
    program.op("movi r1, 1")
    _store(program, 1, WAV_STATE["warnings"])
    _load(program, 1, CTX_FLAGS)
    program.op("movi r2, 1")
    program.op("and r1, r1, r2")
    _store(program, 1, WAV_STATE["strict"])
    _load(program, 1, CTX_INPUT_LENGTH)
    _store(program, 1, WAV_STATE["input_length"])
    program.op("movi r1, 4")
    _store(program, 1, FLAC_STATE["parsing_stage"])
    _store(program, 11, CTX_DIAGNOSTIC)
    program.op("movi r1, 32")
    program.op("call_fwd flac_get_bits")
    program.op("movi r1, 0x664c6143")
    program.op("cmp r15, r1")
    program.op("jump_fwd flac_bad_signature if=ne")

    program.op("movi r1, 128")
    program.op("loop_setup 0, r1")
    program.label("flac_metadata_loop")
    _load(program, 1, FLAC_STATE["metadata_done"])
    program.op("cmp r1, r0")
    program.op("jump_fwd flac_metadata_idle if=ne")
    _store(program, 11, CTX_DIAGNOSTIC)
    program.op("movi r1, 8")
    program.op("call_fwd flac_get_bits")
    program.op("mov r4, r15")
    program.op("movi r1, 7")
    program.op("shr r2, r4, r1")
    _store(program, 2, FLAC_STATE["metadata_done"])
    program.op("movi r1, 0x7f")
    program.op("and r4, r4, r1")
    _store(program, 4, FLAC_STATE["kind"])
    program.op("movi r1, 24")
    program.op("call_fwd flac_get_bits")
    _store(program, 15, FLAC_STATE["frame_remaining"])
    _load(program, 1, FLAC_STATE["metadata_count"])
    program.op("movi r2, 1")
    program.op("add r1, r1, r2")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_metadata_first if=eq")
    _load(program, 4, FLAC_STATE["kind"])
    program.op("cmp r4, r0")
    program.op("jump_fwd flac_bad_metadata if=eq")
    program.op("movi r2, 127")
    program.op("cmp r4, r2")
    program.op("jump_fwd flac_bad_metadata if=eq")
    program.op("movi r2, 7")
    program.op("cmp r4, r2")
    program.op("jump_fwd flac_unsupported_encoding if=uge")
    program.op("jump_fwd flac_metadata_account")
    program.label("flac_metadata_first")
    _load(program, 4, FLAC_STATE["kind"])
    program.op("cmp r4, r0")
    program.op("jump_fwd flac_bad_streaminfo if=ne")
    program.op("movi r2, 5")
    _store(program, 2, CTX_DIAGNOSTIC)
    _load(program, 4, FLAC_STATE["frame_remaining"])
    program.op("movi r2, 34")
    program.op("cmp r4, r2")
    program.op("jump_fwd flac_bad_streaminfo if=ne")
    program.label("flac_metadata_account")
    _store(program, 1, FLAC_STATE["metadata_count"])
    _load(program, 4, CTX_DIAGNOSTIC)
    program.op("movi r2, 1")
    program.op("add r4, r4, r2")
    _store(program, 4, CTX_DIAGNOSTIC)
    _load(program, 2, FLAC_STATE["metadata_bytes"])
    _load(program, 3, FLAC_STATE["frame_remaining"])
    program.op("add r2, r2, r3")
    program.op("cmp r2, r3")
    program.op("jump_fwd flac_profile_limit4 if=ult")
    program.op("movi r3, 0x00100001")
    program.op("cmp r2, r3")
    program.op("jump_fwd flac_profile_limit4 if=uge")
    _store(program, 2, FLAC_STATE["metadata_bytes"])
    _load(program, 4, CTX_DIAGNOSTIC)
    program.op("movi r2, 1")
    program.op("sub r4, r4, r2")
    _store(program, 4, CTX_DIAGNOSTIC)
    program.op("movi r2, 1")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_streaminfo if=eq")
    _load(program, 1, FLAC_STATE["frame_remaining"])
    program.op("call_fwd flac_skip_bytes")
    program.op("jump_fwd flac_metadata_idle")

    program.label("flac_streaminfo")
    for width, destination in (
        (16, "min_block"),
        (16, "max_block"),
        (24, "min_frame"),
        (24, "max_frame"),
        (20, "rate"),
    ):
        program.op(f"movi r1, {width}")
        program.op("call_fwd flac_get_bits")
        _store(
            program,
            15,
            WAV_STATE[destination] if destination == "rate" else FLAC_STATE[destination],
        )
    program.op("movi r1, 3")
    program.op("call_fwd flac_get_bits")
    program.op("movi r1, 1")
    program.op("add r15, r15, r1")
    _store(program, 15, WAV_STATE["channels"])
    program.op("movi r1, 5")
    program.op("call_fwd flac_get_bits")
    program.op("movi r1, 1")
    program.op("add r15, r15, r1")
    _store(program, 15, WAV_STATE["bits"])
    program.op("movi r1, 4")
    program.op("call_fwd flac_get_bits")
    _store(program, 15, FLAC_STATE["total_hi"])
    program.op("movi r1, 32")
    program.op("call_fwd flac_get_bits")
    _store(program, 15, FLAC_STATE["total_lo"])
    for _ in range(4):
        program.op("movi r1, 32")
        program.op("call_fwd flac_get_bits")
    program.op("call_fwd flac_validate_streaminfo")
    program.label("flac_metadata_idle")
    program.op("loop_back 0, flac_metadata_loop")
    _load(program, 1, FLAC_STATE["metadata_done"])
    program.op("cmp r1, r0")
    program.op("jump_fwd flac_profile_limit4 if=eq")
    program.op("call_fwd wav_validate_job_geometry")

    _load(program, 1, WAV_STATE["input_length"])
    program.op("movi r2, 65535")
    program.op("min r1, r1, r2")
    program.op("loop_setup 0, r1")
    program.label("flac_frame_loop")
    program.op("call_fwd flac_terminal_check")
    program.op("cmp r15, r0")
    program.op("jump_fwd flac_frame_idle if=ne")
    _load(program, 1, WAV_STATE["input_length"])
    program.op("cmp r11, r1")
    program.op("jump_fwd flac_sample_count if=uge")
    _store(program, 11, FLAC_STATE["frame_start"])
    _store(program, 11, CTX_DIAGNOSTIC)
    program.op("movi r6, 0")
    program.op("movi r7, 0")
    program.op("movi r8, 3")
    program.op("movi r1, 14")
    program.op("call_fwd flac_get_bits")
    program.op("movi r1, 0x3ffe")
    program.op("cmp r15, r1")
    program.op("jump_fwd flac_bad_frame if=ne")
    program.op("movi r1, 1")
    program.op("call_fwd flac_get_bits")
    program.op("cmp r15, r0")
    program.op("jump_fwd flac_bad_frame if=ne")
    program.op("movi r1, 1")
    program.op("call_fwd flac_get_bits")
    program.op("mov r4, r15")
    _load(program, 1, FLAC_STATE["strategy_seen"])
    program.op("cmp r1, r0")
    program.op("jump_fwd flac_strategy_compare if=ne")
    _store(program, 4, FLAC_STATE["strategy"])
    program.op("movi r1, 1")
    _store(program, 1, FLAC_STATE["strategy_seen"])
    program.op("jump_fwd flac_strategy_ready")
    program.label("flac_strategy_compare")
    _load(program, 1, FLAC_STATE["strategy"])
    program.op("cmp r4, r1")
    program.op("jump_fwd flac_geometry_change if=ne")
    program.label("flac_strategy_ready")
    for width, destination in (
        (4, "kind"),
        (4, "frame_remaining"),
        (4, "assignment"),
        (3, "coded_bits"),
    ):
        program.op(f"movi r1, {width}")
        program.op("call_fwd flac_get_bits")
        _store(program, 15, FLAC_STATE[destination])
    program.op("movi r1, 1")
    program.op("call_fwd flac_get_bits")
    program.op("cmp r15, r0")
    program.op("jump_fwd flac_bad_frame if=ne")
    program.op("call_fwd flac_get_utf8")
    _store(program, 15, FLAC_STATE["parsed_number"])
    _load(program, 1, FLAC_STATE["kind"])
    program.op("call_fwd flac_decode_block_size")
    _store(program, 15, FLAC_STATE["block_size"])
    _load(program, 1, FLAC_STATE["frame_remaining"])
    program.op("call_fwd flac_decode_rate")
    _load(program, 1, WAV_STATE["rate"])
    program.op("cmp r15, r1")
    program.op("jump_fwd flac_geometry_change if=ne")
    _load(program, 1, FLAC_STATE["coded_bits"])
    program.op("call_fwd flac_decode_precision")
    _load(program, 1, WAV_STATE["bits"])
    program.op("cmp r15, r1")
    program.op("jump_fwd flac_geometry_change if=ne")
    program.op("call_fwd flac_validate_frame_header")
    program.op("movi r8, 2")
    program.op("movi r1, 8")
    program.op("call_fwd flac_get_bits")
    program.op("cmp r15, r7")
    program.op("jump_fwd flac_header_crc if=ne")
    program.op("movi r1, 0")
    _store(program, 1, FLAC_STATE["channel"])
    _store(program, 1, FLAC_STATE["output_base"])
    program.op("call_fwd flac_decode_subframe")
    _load(program, 1, WAV_STATE["channels"])
    program.op("movi r2, 2")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_subframes_done if=ne")
    program.op("movi r1, 1")
    _store(program, 1, FLAC_STATE["channel"])
    _load(program, 1, FLAC_STATE["block_size"])
    program.op("movi r2, 2")
    program.op("shl r1, r1, r2")
    _store(program, 1, FLAC_STATE["output_base"])
    program.op("call_fwd flac_decode_subframe")
    program.label("flac_subframes_done")
    program.op("call_fwd flac_align_zero")
    program.op("movi r8, 0")
    program.op("movi r1, 16")
    program.op("call_fwd flac_get_bits")
    program.op("cmp r15, r6")
    program.op("jump_fwd flac_frame_crc if=ne")
    _load(program, 1, FLAC_STATE["frame_start"])
    program.op("sub r2, r11, r1")
    _store(program, 2, FLAC_STATE["frame_input"])
    # Reject advertised or observed frame sizes before decoded samples are
    # released to the conversion and output path.
    program.op("movi r3, 65537")
    program.op("cmp r2, r3")
    program.op("jump_fwd flac_profile_limit4 if=uge")
    _load(program, 3, FLAC_STATE["min_frame"])
    program.op("cmp r3, r0")
    program.op("jump_fwd flac_frame_max_check if=eq")
    program.op("cmp r2, r3")
    program.op("jump_fwd flac_profile_limit4 if=ult")
    program.label("flac_frame_max_check")
    _load(program, 3, FLAC_STATE["max_frame"])
    program.op("cmp r3, r0")
    program.op("jump_fwd flac_frame_profile_ready if=eq")
    program.op("cmp r3, r2")
    program.op("jump_fwd flac_profile_limit4 if=ult")
    program.label("flac_frame_profile_ready")
    _store(program, 0, WAV_STATE["resample_final"])
    _load(program, 1, FLAC_STATE["total_lo"])
    _load(program, 2, FLAC_STATE["total_hi"])
    program.op("or r3, r1, r2")
    program.op("cmp r3, r0")
    program.op("jump_fwd flac_final_unknown if=eq")
    _load(program, 3, FLAC_STATE["decoded_lo"])
    _load(program, 4, FLAC_STATE["block_size"])
    program.op("add r5, r3, r4")
    program.op("cmp r5, r3")
    program.op("movi r6, 1")
    _load(program, 7, FLAC_STATE["decoded_hi"])
    program.op("add r7, r7, r6 if=ult")
    program.op("cmp r2, r7")
    program.op("jump_fwd flac_sample_count if=ult")
    program.op("jump_fwd flac_final_ready if=ne")
    program.op("cmp r1, r5")
    program.op("jump_fwd flac_sample_count if=ult")
    program.op("jump_fwd flac_final_ready if=ne")
    _store(program, 6, WAV_STATE["resample_final"])
    program.op("jump_fwd flac_final_ready")
    program.label("flac_final_unknown")
    _load(program, 1, WAV_STATE["input_length"])
    program.op("cmp r11, r1")
    program.op("movi r2, 1")
    program.op(f"st32 r0, r2, 0x{WAV_STATE['resample_final']:04x} if=eq")
    program.label("flac_final_ready")
    _load(program, 1, WAV_STATE["resample_final"])
    program.op("cmp r1, r0")
    program.op("jump_fwd flac_block_profile_ready if=ne")
    _load(program, 1, FLAC_STATE["block_size"])
    _load(program, 2, FLAC_STATE["min_block"])
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_profile_limit4 if=ult")
    program.label("flac_block_profile_ready")
    program.op("call_fwd flac_process_frame")
    _load(program, 1, FLAC_STATE["decoded_lo"])
    _load(program, 2, FLAC_STATE["block_size"])
    program.op("add r3, r1, r2")
    program.op("cmp r3, r1")
    program.op("movi r4, 1")
    _load(program, 5, FLAC_STATE["decoded_hi"])
    program.op("add r5, r5, r4 if=ult")
    _store(program, 3, FLAC_STATE["decoded_lo"])
    _store(program, 5, FLAC_STATE["decoded_hi"])
    _load(program, 1, FLAC_STATE["expected_number"])
    program.op("movi r2, 1")
    program.op("add r1, r1, r2")
    _store(program, 1, FLAC_STATE["expected_number"])
    program.label("flac_frame_idle")
    program.op("loop_back 0, flac_frame_loop")
    program.op("call_fwd flac_terminal_check")
    program.op("cmp r15, r0")
    program.op("jump_fwd flac_profile_limit4 if=eq")
    _load(program, 1, WAV_STATE["pending"])
    program.op("cmp r1, r0")
    program.op("jump_fwd flac_success if=eq")
    program.op("movi r1, 1")
    _store(program, 1, CTX_FINAL)
    program.op("call_fwd flac_emit_pending")
    program.label("flac_success")
    program.op("movi r4, 0")
    program.op("movi r5, 0x02010000")
    program.op("job_result r4, r5, 0")
    program.op("end")


def _emit_flac_helpers(program: Program) -> None:
    """Emit forward-only FLAC parser, reconstruction, and reader helpers."""

    program.label("flac_validate_streaminfo")
    program.op("movi r6, 8")
    _store(program, 6, CTX_DIAGNOSTIC)
    _load(program, 1, FLAC_STATE["min_block"])
    program.op("movi r2, 16")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_profile_limit4 if=ult")
    program.op("movi r6, 10")
    _store(program, 6, CTX_DIAGNOSTIC)
    _load(program, 2, FLAC_STATE["max_block"])
    program.op("cmp r2, r1")
    program.op("jump_fwd flac_bad_streaminfo if=ult")
    _load(program, 3, WAV_STATE["channels"])
    program.op("movi r4, 1")
    program.op("cmp r3, r4")
    program.op("jump_fwd flac_streaminfo_mono if=eq")
    program.op("movi r4, 2")
    program.op("cmp r3, r4")
    program.op("jump_fwd flac_streaminfo_frame_hints if=ne")
    program.op("movi r4, 2049")
    program.op("jump_fwd flac_streaminfo_block_limit")
    program.label("flac_streaminfo_mono")
    program.op("movi r4, 4097")
    program.label("flac_streaminfo_block_limit")
    program.op("cmp r2, r4")
    program.op("jump_fwd flac_profile_limit4 if=uge")
    program.label("flac_streaminfo_frame_hints")
    program.op("movi r6, 15")
    _store(program, 6, CTX_DIAGNOSTIC)
    _load(program, 1, FLAC_STATE["min_frame"])
    _load(program, 2, FLAC_STATE["max_frame"])
    program.op("cmp r1, r0")
    program.op("jump_fwd flac_streaminfo_max_frame if=eq")
    program.op("cmp r2, r0")
    program.op("jump_fwd flac_streaminfo_max_frame if=eq")
    program.op("cmp r2, r1")
    program.op("jump_fwd flac_bad_streaminfo if=ult")
    program.label("flac_streaminfo_max_frame")
    program.op("movi r3, 65537")
    program.op("cmp r2, r3")
    program.op("jump_fwd flac_profile_limit4 if=uge")
    program.op("movi r6, 18")
    _store(program, 6, CTX_DIAGNOSTIC)
    _load(program, 3, WAV_STATE["channels"])
    program.op("movi r4, 1")
    program.op("cmp r3, r4")
    program.op("jump_fwd flac_streaminfo_geometry_channels if=eq")
    program.op("movi r4, 2")
    program.op("cmp r3, r4")
    program.op("jump_fwd flac_unsupported_geometry if=ne")
    program.label("flac_streaminfo_geometry_channels")
    _load(program, 1, WAV_STATE["rate"])
    program.op("movi r2, 8000")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_unsupported_geometry if=ult")
    program.op("movi r2, 96001")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_unsupported_geometry if=uge")
    _load(program, 1, WAV_STATE["bits"])
    program.op("movi r2, 16")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_streaminfo_valid if=eq")
    program.op("movi r2, 24")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_unsupported_geometry if=ne")
    program.label("flac_streaminfo_valid")
    program.op("ret")

    program.label("flac_terminal_check")
    _load(program, 1, FLAC_STATE["total_lo"])
    _load(program, 2, FLAC_STATE["total_hi"])
    program.op("or r3, r1, r2")
    program.op("cmp r3, r0")
    program.op("jump_fwd flac_terminal_unknown if=eq")
    _load(program, 3, FLAC_STATE["decoded_hi"])
    program.op("cmp r3, r2")
    program.op("jump_fwd flac_terminal_not_done if=ne")
    _load(program, 3, FLAC_STATE["decoded_lo"])
    program.op("cmp r3, r1")
    program.op("jump_fwd flac_terminal_not_done if=ne")
    program.op("movi r15, 1")
    program.op("ret")
    program.label("flac_terminal_unknown")
    _load(program, 1, WAV_STATE["input_length"])
    program.op("cmp r11, r1")
    program.op("movi r15, 1 if=eq")
    program.op("movi r15, 0 if=ne")
    program.op("ret")
    program.label("flac_terminal_not_done")
    program.op("movi r15, 0")
    program.op("ret")

    program.label("flac_decode_block_size")
    program.op("cmp r1, r0")
    program.op("jump_fwd flac_bad_frame if=eq")
    program.op("movi r2, 1")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_block_192 if=eq")
    program.op("movi r2, 6")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_block_byte if=eq")
    program.op("movi r2, 7")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_block_word if=eq")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_block_fixed if=ult")
    program.op("movi r2, 8")
    program.op("sub r2, r1, r2")
    program.op("movi r15, 256")
    program.op("shl r15, r15, r2")
    program.op("ret")
    program.label("flac_block_fixed")
    program.op("movi r2, 2")
    program.op("sub r2, r1, r2")
    program.op("movi r15, 576")
    program.op("shl r15, r15, r2")
    program.op("ret")
    program.label("flac_block_192")
    program.op("movi r15, 192")
    program.op("ret")
    program.label("flac_block_byte")
    program.op("movi r1, 8")
    program.op("call_fwd flac_get_bits")
    program.op("movi r1, 1")
    program.op("add r15, r15, r1")
    program.op("ret")
    program.label("flac_block_word")
    program.op("movi r1, 16")
    program.op("call_fwd flac_get_bits")
    program.op("movi r1, 1")
    program.op("add r15, r15, r1")
    program.op("ret")

    program.label("flac_decode_rate")
    program.op("cmp r1, r0")
    program.op("jump_fwd flac_rate_streaminfo if=eq")
    for code, rate in (
        (1, 88200),
        (2, 176400),
        (3, 192000),
        (4, 8000),
        (5, 16000),
        (6, 22050),
        (7, 24000),
        (8, 32000),
        (9, 44100),
        (10, 48000),
        (11, 96000),
    ):
        program.op(f"movi r2, {code}")
        program.op("cmp r1, r2")
        program.op(f"jump_fwd flac_rate_{rate} if=eq")
    program.op("movi r2, 12")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_rate_khz if=eq")
    program.op("movi r2, 13")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_rate_hz if=eq")
    program.op("movi r2, 14")
    program.op("cmp r1, r2")
    program.op("jump_fwd flac_rate_ten_hz if=eq")
    program.op("jump_fwd flac_bad_frame")
    program.label("flac_rate_streaminfo")
    _load(program, 15, WAV_STATE["rate"])
    program.op("ret")
    for _, rate in (
        (1, 88200),
        (2, 176400),
        (3, 192000),
        (4, 8000),
        (5, 16000),
        (6, 22050),
        (7, 24000),
        (8, 32000),
        (9, 44100),
        (10, 48000),
        (11, 96000),
    ):
        program.label(f"flac_rate_{rate}")
        program.op(f"movi r15, {rate}")
        program.op("ret")
    program.label("flac_rate_khz")
    program.op("movi r1, 8")
