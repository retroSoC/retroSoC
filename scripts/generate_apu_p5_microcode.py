class Program:
    """Small deterministic emitter for the frozen text microassembly syntax."""

    def __init__(self) -> None:
        self.lines: list[str] = []

    def line(self, value: str = "") -> None:
        self.lines.append(value)

    def label(self, name: str) -> None:
        self.lines.append(f"{name}:")

    def op(self, operation: str) -> None:
        self.lines.append(f"  {operation}")

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


