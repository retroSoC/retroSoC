def _store(program: Program, register: int, offset: int) -> None:
    program.op(f"st32 r0, r{register}, 0x{offset:04x}")


def _load(program: Program, register: int, offset: int) -> None:
    program.op(f"ld32 r{register}, r0, 0x{offset:04x}")


def _fail(program: Program, code: int, reason: int, label: str = "wav_fail") -> None:
    program.op(f"movi r4, {code}")
    program.op(f"movi r5, 0x{reason:04x}")
    program.op(f"jump_fwd {label}")


def _compare_fail(
    program: Program,
    left: int,
    right: int,
    predicate: str,
    code: int,
    reason: int,
) -> None:
    ok = f"wav_check_ok_{len(program.lines)}"
    program.op(f"cmp r{left}, r{right}")
    inverse = {
        "eq": "ne",
        "ne": "eq",
        "ult": "uge",
        "uge": "ult",
        "slt": "sge",
        "sge": "slt",
    }[predicate]
    program.op(f"jump_fwd {ok} if={inverse}")
    _fail(program, code, reason)
    program.label(ok)


def _emit_wav(program: Program) -> None:
    # r9..r15 are the byte-reader state: bit byte/count, parsed count,
    # FIFO word/valid bytes, refill bytes, and return value.
    program.label("wav")
    program.op("movi r0, 0")
    program.op("movi r1, 0x4400")
    program.op("movi r2, 208")
    program.op("loop_setup 0, r2")
    program.label("wav_state_clear_loop")
    program.op("st32 r1, r0, 0")
    program.op("movi r3, 4")
    program.op("add r1, r1, r3")
    program.op("loop_back 0, wav_state_clear_loop")
    _load(program, 1, CTX_FLAGS)
    program.op("movi r2, 1")
    program.op("and r1, r1, r2")
    _store(program, 1, WAV_STATE["strict"])
    _load(program, 1, CTX_INPUT_LENGTH)
    _store(program, 1, WAV_STATE["input_length"])

    _store(program, 11, CTX_DIAGNOSTIC)
    program.op("call_fwd wav_get_u32le")
    program.op("movi r1, 0x46464952")
    _compare_fail(program, 15, 1, "ne", 4, 0x0010)
    _store(program, 11, CTX_DIAGNOSTIC)
    program.op("call_fwd wav_get_u32le")
    program.op("movi r1, 8")
    program.op("add r2, r15, r1")
    program.op("cmp r2, r15")
    program.op("jump_fwd wav_bad_extent if=ult")
    program.op("movi r1, 12")
    program.op("cmp r2, r1")
    program.op("jump_fwd wav_bad_extent if=ult")
    _load(program, 1, WAV_STATE["input_length"])
    program.op("cmp r1, r2")
    program.op("jump_fwd wav_bad_extent if=ult")
    program.label("wav_riff_bound_ok")
    _store(program, 2, WAV_STATE["riff_end"])
    _store(program, 11, CTX_DIAGNOSTIC)
    program.op("call_fwd wav_get_u32le")
    program.op("movi r1, 0x45564157")
    _compare_fail(program, 15, 1, "ne", 4, 0x0010)

    # Each chunk consumes at least one byte; cap the frozen 1024-chunk bound
    # by the input length so short files do not spin through idle iterations.
    _load(program, 1, WAV_STATE["input_length"])
    program.op("movi r2, 1024")
    program.op("min r1, r1, r2")
    program.op("loop_setup 0, r1")
    program.label("wav_chunk_loop")
    _load(program, 1, WAV_STATE["riff_end"])
    program.op("cmp r11, r1")
    program.op("jump_fwd wav_chunk_idle if=eq")
    program.op("sub r2, r1, r11")
    program.op("movi r3, 8")
    program.op("cmp r2, r3")
    program.op("jump_fwd wav_truncated if=ult")
    _store(program, 11, CTX_DIAGNOSTIC)
    program.op("call_fwd wav_get_u32le")
    program.op("mov r4, r15")
    program.op("call_fwd wav_get_u32le")
    program.op("mov r5, r15")
    _store(program, 5, WAV_STATE["chunk_size"])
    program.op("add r6, r11, r5")
    program.op("cmp r6, r11")
    program.op("jump_fwd wav_bad_chunk if=ult")
    program.op("movi r7, 1")
    program.op("and r7, r5, r7")
    _store(program, 7, WAV_STATE["chunk_pad"])
    program.op("add r8, r6, r7")
    program.op("cmp r8, r6")
    program.op("jump_fwd wav_bad_chunk if=ult")
    _load(program, 1, WAV_STATE["riff_end"])
    program.op("cmp r1, r8")
    program.op("jump_fwd wav_bad_chunk if=ult")
    program.label("wav_chunk_bound_ok")
    _load(program, 1, WAV_STATE["chunk_count"])
    program.op("movi r2, 1")
    program.op("add r1, r1, r2")
    _store(program, 1, WAV_STATE["chunk_count"])
    program.op("movi r1, 0x20746d66")
    program.op("cmp r4, r1")
    program.op("jump_fwd wav_fmt_chunk if=eq")
    program.op("movi r1, 0x61746164")
    program.op("cmp r4, r1")
    program.op("jump_fwd wav_data_chunk if=eq")
    _load(program, 1, WAV_STATE["skipped"])
    _load(program, 2, WAV_STATE["chunk_size"])
    _load(program, 3, WAV_STATE["chunk_pad"])
    program.op("add r2, r2, r3")
    program.op("add r1, r1, r2")
    program.op("cmp r1, r2")
    program.op("jump_fwd wav_bad_chunk if=ult")
    program.op("movi r3, 0x00100001")
    program.op("cmp r1, r3")
    program.op("jump_fwd wav_profile_limit if=uge")
    _store(program, 1, WAV_STATE["skipped"])
    _load(program, 1, WAV_STATE["chunk_size"])
    program.op("call_fwd wav_skip_bytes")
    program.op("jump_fwd wav_chunk_padding")

    program.label("wav_fmt_chunk")
    _load(program, 1, WAV_STATE["fmt_seen"])
    _load(program, 2, WAV_STATE["data_seen"])
    program.op("or r1, r1, r2")
    program.op("cmp r1, r0")
    program.op("jump_fwd wav_required_chunk if=ne")
    program.op("movi r1, 16")
    program.op("cmp r5, r1")
    program.op("jump_fwd wav_fmt_size_ok if=eq")
    program.op("movi r1, 18")
    program.op("cmp r5, r1")
    program.op("jump_fwd wav_fmt_size_ok if=eq")
    program.op("movi r1, 40")
    program.op("cmp r5, r1")
    program.op("jump_fwd wav_fmt_size_ok if=eq")
    _fail(program, 4, 0x0014)
    program.label("wav_fmt_size_ok")
    program.op("call_fwd wav_get_u16le")
    program.op("mov r4, r15")
    program.op("call_fwd wav_get_u16le")
    program.op("mov r3, r15")
    _store(program, 3, WAV_STATE["channels"])
    program.op("call_fwd wav_get_u32le")
    _store(program, 15, WAV_STATE["rate"])
    program.op("call_fwd wav_get_u32le")
    program.op("mov r2, r15")
    _store(program, 2, WAV_STATE["average_rate"])
    program.op("call_fwd wav_get_u16le")
    program.op("mov r6, r15")
    _store(program, 6, WAV_STATE["align"])
    program.op("call_fwd wav_get_u16le")
    program.op("mov r7, r15")
    _store(program, 7, WAV_STATE["bits"])
    program.op("movi r1, 1")
    program.op("cmp r4, r1")
    program.op("jump_fwd wav_pcm_fmt if=eq")
    program.op("movi r1, 0xfffe")
    program.op("cmp r4, r1")
    program.op("jump_fwd wav_extensible_fmt if=eq")
    _fail(program, 3, 0x0003)

    program.label("wav_pcm_fmt")
    program.op("movi r1, 40")
    program.op("cmp r5, r1")
    program.op("jump_fwd wav_bad_format if=eq")
    program.op("movi r1, 18")
    program.op("cmp r5, r1")
    program.op("jump_fwd wav_pcm_cbsize if=eq")
    program.op("jump_fwd wav_validate_fmt")
    program.label("wav_pcm_cbsize")
    program.op("call_fwd wav_get_u16le")
    program.op("cmp r15, r0")
    program.op("jump_fwd wav_bad_format if=ne")
    program.op("jump_fwd wav_validate_fmt")

    program.label("wav_extensible_fmt")
    program.op("movi r1, 40")
    program.op("cmp r5, r1")
    program.op("jump_fwd wav_unsupported_encoding if=ne")
    program.op("call_fwd wav_get_u16le")
    program.op("movi r1, 22")
    program.op("cmp r15, r1")
    program.op("jump_fwd wav_unsupported_encoding if=ne")
    program.op("call_fwd wav_get_u16le")
    program.op("cmp r15, r7")
    program.op("jump_fwd wav_unsupported_encoding if=ne")
    program.op("call_fwd wav_get_u32le")
    program.op("mov r4, r15")
    program.op("movi r1, 1")
    program.op("cmp r3, r1")
    program.op("jump_fwd wav_extensible_mono if=eq")
    program.op("cmp r4, r0")
    program.op("jump_fwd wav_extensible_guid if=eq")
    program.op("movi r1, 3")
    program.op("cmp r4, r1")
    program.op("jump_fwd wav_unsupported_encoding if=ne")
    program.op("jump_fwd wav_extensible_guid")
    program.label("wav_extensible_mono")
    program.op("cmp r4, r0")
    program.op("jump_fwd wav_extensible_guid if=eq")
    program.op("movi r1, 4")
    program.op("cmp r4, r1")
    program.op("jump_fwd wav_unsupported_encoding if=ne")
    program.label("wav_extensible_guid")
    for expected in (0x00000001, 0x00100000, 0xAA000080, 0x719B3800):
        program.op("call_fwd wav_get_u32le")
        program.op(f"movi r1, 0x{expected:08x}")
        program.op("cmp r15, r1")
        program.op("jump_fwd wav_unsupported_encoding if=ne")

    program.label("wav_validate_fmt")
    program.op("movi r1, 1")
    program.op("cmp r3, r1")
    program.op("jump_fwd wav_channels_ok if=eq")
    program.op("movi r1, 2")
    program.op("cmp r3, r1")
    program.op("jump_fwd wav_bad_format if=ne")
    program.label("wav_channels_ok")
    _load(program, 1, WAV_STATE["rate"])
    program.op("movi r4, 8000")
    program.op("cmp r1, r4")
    program.op("jump_fwd wav_bad_format if=ult")
    program.op("movi r4, 96001")
    program.op("cmp r1, r4")
    program.op("jump_fwd wav_bad_format if=uge")
    program.op("movi r1, 8")
    program.op("cmp r7, r1")
    program.op("jump_fwd wav_bits_divide if=eq")
    program.op("movi r1, 16")
    program.op("cmp r7, r1")
    program.op("jump_fwd wav_bits_divide if=eq")
    program.op("movi r1, 24")
    program.op("cmp r7, r1")
    program.op("jump_fwd wav_bits_divide if=eq")
    program.op("movi r1, 32")
    program.op("cmp r7, r1")
    program.op("jump_fwd wav_bad_format if=ne")
    program.label("wav_bits_divide")
    program.op("movi r1, 3")
    program.op("shr r4, r7, r1")
    program.op("movi r1, 2")
    program.op("cmp r3, r1")
    program.op("movi r1, 1")
    program.op("shl r4, r4, r1 if=eq")
    _load(program, 6, WAV_STATE["align"])
    program.op("cmp r6, r4")
    program.op("jump_fwd wav_bad_format if=ne")
    _load(program, 1, WAV_STATE["rate"])
    program.op("movi r3, 1")
    program.op("cmp r4, r3")
    program.op("jump_fwd wav_average_ready if=eq")
    program.op("movi r3, 2")
    program.op("cmp r4, r3")
    program.op("movi r3, 1")
    program.op("shl r1, r1, r3 if=eq")
    program.op("jump_fwd wav_average_ready if=eq")
    program.op("movi r3, 3")
    program.op("cmp r4, r3")
    program.op("jump_fwd wav_average_three if=eq")
    program.op("movi r3, 4")
    program.op("cmp r4, r3")
    program.op("movi r3, 2")
    program.op("shl r1, r1, r3 if=eq")
    program.op("jump_fwd wav_average_ready if=eq")
    program.op("movi r3, 6")
    program.op("cmp r4, r3")
    program.op("jump_fwd wav_average_six if=eq")
    program.op("movi r3, 3")
    program.op("shl r1, r1, r3")
    program.op("jump_fwd wav_average_ready")
    program.label("wav_average_three")
    program.op("movi r3, 1")
    program.op("shl r2, r1, r3")
    program.op("add r1, r1, r2")
    program.op("jump_fwd wav_average_ready")
    program.label("wav_average_six")
    program.op("movi r3, 2")
    program.op("shl r2, r1, r3")
    program.op("movi r3, 1")
    program.op("shl r1, r1, r3")
    program.op("add r1, r1, r2")
    program.label("wav_average_ready")
    _load(program, 2, WAV_STATE["average_rate"])
    program.op("cmp r2, r1")
    program.op("jump_fwd wav_bad_format if=ne")
    program.op("movi r1, 1")
    _store(program, 1, WAV_STATE["fmt_seen"])
    program.op("jump_fwd wav_chunk_padding")

    program.label("wav_data_chunk")
    _load(program, 5, WAV_STATE["chunk_size"])
    _load(program, 1, WAV_STATE["fmt_seen"])
    _load(program, 2, WAV_STATE["data_seen"])
    program.op("movi r3, 1")
    program.op("cmp r1, r3")
    program.op("jump_fwd wav_required_chunk if=ne")
    program.op("cmp r2, r0")
    program.op("jump_fwd wav_required_chunk if=ne")
    _load(program, 1, WAV_STATE["align"])
    program.op("mov r2, r5")
    program.op("call_fwd wav_validate_alignment")
    program.op("movi r1, 1")
    _store(program, 1, WAV_STATE["data_seen"])
    _load(program, 5, WAV_STATE["chunk_size"])
    _store(program, 5, WAV_STATE["data_remaining"])
    program.op("call_fwd wav_validate_job_geometry")
    _load(program, 1, WAV_STATE["profile"])
    program.op("cmp r1, r0")
    program.op("jump_fwd wav_data_passthrough if=eq")
    program.op("call_fwd wav_process_resampled")
    program.op("jump_fwd wav_data_done")
    program.label("wav_data_passthrough")
    _load(program, 1, WAV_STATE["data_remaining"])
    program.op("cmp r1, r0")
    program.op("jump_fwd wav_data_done if=eq")
    _load(program, 2, WAV_STATE["align"])
    program.op("movi r3, 0")
    program.op("movi r4, 65535")
    program.op("min r4, r1, r4")
    program.op("loop_setup 1, r4")
    program.label("wav_tile_count_loop")
    program.op("cmp r1, r2")
    program.op("sub r1, r1, r2 if=uge")
    program.op("movi r5, 1")
    program.op("add r3, r3, r5 if=uge")
    program.op("loop_back 1, wav_tile_count_loop")
    program.op("cmp r1, r0")
    program.op("movi r1, 65535 if=ne")
    program.op("jump_fwd wav_tile_count_ready if=ne")
    program.op("movi r1, 31")
    program.op("add r3, r3, r1")
    program.op("movi r1, 5")
    program.op("shr r1, r3, r1")
    program.label("wav_tile_count_ready")
    program.op("loop_setup 1, r1")
    program.label("wav_data_tile_loop")
    _load(program, 1, WAV_STATE["data_remaining"])
    program.op("cmp r1, r0")
    program.op("jump_fwd wav_data_tile_idle if=eq")
    _load(program, 1, WAV_STATE["data_remaining"])
    # Select min(32, remaining/alignment) without division. Stereo S24 then
    # fills the frozen 256-byte maximum output command exactly.
    program.op("movi r2, 0")
    _load(program, 3, WAV_STATE["align"])
    program.op("mov r4, r1")
    program.op("movi r5, 32")
    program.op("loop_setup 2, r5")
    program.label("wav_tile_size_loop")
    program.op("cmp r4, r3")
    program.op("sub r4, r4, r3 if=uge")
    program.op("movi r6, 1")
    program.op("add r2, r2, r6 if=uge")
    program.op("loop_back 2, wav_tile_size_loop")
    program.op("cmp r2, r0")
    program.op("jump_fwd wav_bad_chunk if=eq")
    _store(program, 2, WAV_STATE["tile_frames"])
    _store(program, 2, WAV_STATE["source_tile_frames"])
    program.op("movi r1, 0")
    program.op("loop_setup 2, r2")
    program.label("wav_read_tile_loop")
    program.op("call_fwd wav_read_frame")
    program.op("loop_back 2, wav_read_tile_loop")
    _store(program, 0, WAV_STATE["pack_input"])
    program.op("movi r1, 32")
    _store(program, 1, WAV_STATE["pack_capacity"])
    _load(program, 1, WAV_STATE["source_tile_frames"])
    _load(program, 2, WAV_STATE["align"])
    # Multiply the bounded source-frame count by the validated block alignment.
    program.op("movi r3, 0")
    program.op("loop_setup 2, r1")
    program.label("wav_tile_input_loop")
    program.op("add r3, r3, r2")
    program.op("loop_back 2, wav_tile_input_loop")
    _load(program, 4, WAV_STATE["uncommitted_input"])
    program.op("add r4, r4, r3")
    _store(program, 4, WAV_STATE["uncommitted_input"])
    _load(program, 4, WAV_STATE["data_remaining"])
    program.op("sub r4, r4, r3")
    _store(program, 4, WAV_STATE["data_remaining"])
    program.op("call_fwd wav_pack_tile")
    program.label("wav_data_tile_idle")
    program.op("loop_back 1, wav_data_tile_loop")
    # More than 65535 32-frame tiles is outside the bounded release program.
    _load(program, 1, WAV_STATE["data_remaining"])
    program.op("cmp r1, r0")
    program.op("jump_fwd wav_profile_limit if=ne")
